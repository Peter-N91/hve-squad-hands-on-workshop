// Pins the guide to the latest stable HVE Squad release.
// Asks GitHub for Peter-N91/hve-squad's latest release (pre-releases excluded) and writes
// src/hve-squad-release.ts. Runs before dev, build and the starter package, so every published
// build names, installs and links the current release. Offline, rate-limited or with
// HVE_SQUAD_RELEASE_OFFLINE=1 it keeps the committed file and says so.
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

export const repository = 'Peter-N91/hve-squad'
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
export const releaseFile = join(root, 'src', 'hve-squad-release.ts')
const semver = /^v?(\d+\.\d+\.\d+)$/

export function parseRelease(json) {
  if (!json || json.draft || json.prerelease) throw new Error('the latest release is a draft or a pre-release')
  const match = semver.exec(String(json.tag_name ?? ''))
  if (!match) throw new Error(`unexpected release tag ${JSON.stringify(json.tag_name)}`)
  return { version: match[1], tag: json.tag_name, url: json.html_url, publishedAt: json.published_at }
}

export function renderReleaseModule(release) {
  return `// Generated by scripts/hve-squad-release.mjs from the latest stable ${repository} release. Do not edit.\n`
    + `export const hveSquadRelease = ${JSON.stringify(release, null, 2)} as const\n`
}

export async function readCommittedRelease() {
  const text = await readFile(releaseFile, 'utf8')
  const json = text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1)
  return JSON.parse(json)
}

export async function resolveRelease({ fetchImpl = fetch, token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN } = {}) {
  const headers = { accept: 'application/vnd.github+json', 'user-agent': 'hve-squad-hands-on-workshop' }
  if (token) headers.authorization = `Bearer ${token}`
  const response = await fetchImpl(`https://api.github.com/repos/${repository}/releases/latest`, { headers, signal: AbortSignal.timeout(10000) })
  if (!response.ok) throw new Error(`GitHub answered HTTP ${response.status}`)
  return parseRelease(await response.json())
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const committed = await readCommittedRelease()
  if (process.env.HVE_SQUAD_RELEASE_OFFLINE === '1') {
    console.log(`HVE Squad release: v${committed.version} (offline, committed value)`)
  } else {
    try {
      const latest = await resolveRelease()
      if (latest.version !== committed.version || latest.url !== committed.url) {
        await writeFile(releaseFile, renderReleaseModule(latest))
        console.log(`HVE Squad release: v${latest.version} (updated from v${committed.version})`)
      } else console.log(`HVE Squad release: v${latest.version} (latest)`)
    } catch (error) {
      console.warn(`HVE Squad release: v${committed.version} (could not check the latest release: ${error instanceof Error ? error.message : error})`)
    }
  }
}
